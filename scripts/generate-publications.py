#!/usr/bin/env python3
"""
Build publications.qmd from data/publications.bib.

Run from the repo root (CI step, before `quarto render`):
    python3 scripts/generate-publications.py

Uses only the standard library plus the pandoc bundled with Quarto
(`quarto pandoc`), falling back to a plain `pandoc` if Quarto isn't on PATH.

Inputs:
    data/publications.bib        master list (entries tagged via `keywords`)
    data/csl/apa.csl             citation style
    data/publications-intro.md   optional text shown at the top of the page
Output:
    publications.qmd             generated; gitignored, do not edit
"""
import datetime
import os
import re
import shutil
import subprocess
import sys
import tempfile

ROOT = os.getcwd()
BIB = os.path.join(ROOT, "data", "publications.bib")
CSL = os.path.join(ROOT, "data", "csl", "apa.csl")
INTRO = os.path.join(ROOT, "data", "publications-intro.md")
OUT = os.path.join(ROOT, "publications.qmd")

# Tabs on the page: (tab title, categories it holds)
TABS = [
    ("Journal articles", ["journal"]),
    ("Conference papers", ["conference-paper"]),
    ("Conference abstracts", ["conference-abstract"]),
    ("Theses and other", ["thesis", "book-chapter", "preprint", "outreach", "other"]),
]
LABELS = {"thesis": "Theses", "book-chapter": "Book chapters", "preprint": "Preprints",
          "outreach": "Outreach", "other": "Other"}

# How your name appears after APA formatting; bolded on the page
SELF = re.compile(r"Marshall, A\.(?: T\.)?")


def pandoc_cmd():
    if shutil.which("quarto"):
        return ["quarto", "pandoc"]
    if shutil.which("pandoc"):
        return ["pandoc"]
    sys.exit("Neither quarto nor pandoc found on PATH")


def read_entries(path):
    """Split a .bib into entries; pull out key, year and category tags."""
    text = open(path, encoding="utf-8").read()
    entries = []
    for chunk in re.split(r"(?m)^(?=@)", text):
        m = re.match(r"@\w+\{([^,]+),", chunk)
        if not m:
            continue
        year = re.search(r"(?m)^\s*year\s*=\s*\{(\d{4})\}", chunk)
        kw = re.search(r"(?m)^\s*keywords\s*=\s*\{([^}]*)\}", chunk)
        entries.append({
            "key": m.group(1).strip(),
            "year": int(year.group(1)) if year else 0,
            "tags": [k.strip() for k in kw.group(1).split(",")] if kw else ["other"],
            "raw": chunk.strip() + "\n",
        })
    return entries


def format_entries(entries, pandoc):
    """Format a group of entries in the CSL style; return markdown entry divs."""
    if not entries:
        return ""
    with tempfile.TemporaryDirectory() as tmp:
        bib = os.path.join(tmp, "group.bib")
        with open(bib, "w", encoding="utf-8") as fh:
            fh.write("\n".join(e["raw"] for e in entries))
        doc = "---\nnocite: '@*'\n---\n"
        res = subprocess.run(
            pandoc + ["--citeproc", f"--bibliography={bib}", f"--csl={CSL}",
                      "-f", "markdown", "-t", "markdown-citations", "--wrap=none"],
            input=doc, capture_output=True, text=True)
    if res.returncode != 0:
        sys.exit(f"pandoc failed:\n{res.stderr}")
    # Keep the per-entry divs, drop pandoc's outer #refs wrapper
    lines = res.stdout.splitlines()
    body = [l for l in lines if not re.match(r"^:{3,}\s*\{#refs", l)]
    if body and re.match(r"^:{3,}\s*$", body[-1]):
        body = body[:-1]
    md = "\n".join(body).strip()
    # drop APA same-author-same-year letters (2023a); they only make sense in-text
    md = re.sub(r"\((\d{4})[a-z]\)", r"(\1)", md)
    return SELF.sub(lambda m: f"**{m.group(0)}**", md)


def section(entries, pandoc, heading_level):
    """Year headings (newest first), each with its APA-formatted entries."""
    out = []
    years = sorted({e["year"] for e in entries}, reverse=True)
    for y in years:
        group = [e for e in entries if e["year"] == y]
        out.append(f"{'#' * heading_level} {y if y else 'Undated'}\n")
        out.append("::: {.references .csl-bib-body .hanging-indent}\n")
        out.append(format_entries(group, pandoc) + "\n")
        out.append(":::\n")
    return "\n".join(out)


def main():
    pandoc = pandoc_cmd()
    entries = read_entries(BIB)

    def in_cats(cats):
        return [e for e in entries if any(t in cats for t in e["tags"])]

    counts = {title: len(in_cats(cats)) for title, cats in TABS}
    today = datetime.date.today().strftime("%d %B %Y").lstrip("0")

    parts = ["---", 'title: "Publications"', "page-layout: full", "---",
             "<!-- Generated by scripts/generate-publications.py from data/publications.bib."
             " Do not edit. -->", ""]
    if os.path.exists(INTRO):
        parts.append(open(INTRO, encoding="utf-8").read().strip() + "\n")
    summary = ", ".join(f"{n} {t.lower()}" for t, n in counts.items() if n)
    parts.append(f"*Last updated {today}. {summary}.*\n")

    parts.append("::: {.panel-tabset}\n")
    for title, cats in TABS:
        group = in_cats(cats)
        if not group:
            continue
        parts.append(f"## {title} ({len(group)})\n")
        if len(cats) == 1:
            parts.append(section(group, pandoc, 3))
        else:  # mixed tab: a sub-heading per category, entries newest first
            for c in cats:
                sub = [e for e in group if c in e["tags"]]
                if sub:
                    parts.append(f"### {LABELS.get(c, c)}\n")
                    sub.sort(key=lambda e: -e["year"])
                    parts.append("::: {.references .csl-bib-body .hanging-indent}\n")
                    for e in sub:  # one at a time to keep newest-first order
                        parts.append(format_entries([e], pandoc) + "\n")
                    parts.append(":::\n")
    parts.append(":::\n")

    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write("\n".join(parts))
    print(f"Wrote {OUT}: " + ", ".join(f"{t} {n}" for t, n in counts.items()))


if __name__ == "__main__":
    main()
